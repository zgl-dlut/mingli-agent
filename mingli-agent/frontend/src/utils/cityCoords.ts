/**
 * 根据省份和城市名查询经纬度
 * 查询顺序：市级 → 省级 → 北京默认 + warn
 */
export function getCityCoord(provinceName: string, cityName: string): Coord {
  if (cityName && CITY_COORDS[cityName]) {
    return CITY_COORDS[cityName]
  }
  if (provinceName && PROVINCE_COORDS[provinceName]) {
    console.warn(`[cityCoords] 城市 "${cityName}" 无精确经纬度，回退省级 "${provinceName}"`)
    return PROVINCE_COORDS[provinceName]
  }
  console.warn(`[cityCoords] 省份 "${provinceName}" 城市 "${cityName}" 均无经纬度，回退北京默认`)
  return DEFAULT_COORD
}
