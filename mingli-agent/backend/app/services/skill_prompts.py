def _build_context_vars(
    analysis_data: Dict,
    gender: str,
    user_question: str,
    birth_date: str = "",
) -> Dict[str, str]:
    """
    从 analysis_data 中提取所有需要的命盘字段，构建模板变量字典。
    """
    time_info = _get_current_time_info()

    # 提取四柱
    sizu = analysis_data.get("四柱", "")
    if sizu:
        parts = sizu.split() if isinstance(sizu, str) else ["", "", "", ""]
        if len(parts) == 4:
            sizu = f"{parts[0]} {parts[1]} {parts[2]} {parts[3]}"

    # 提取当前大运干支
    current_dayun_raw = analysis_data.get("当前大运", "")
    current_dayun_ganzhi = _extract_dayun_ganzhi(current_dayun_raw)

    # 五行分布格式化
    wuxing_fenbu = analysis_data.get("五行分布", {})
    wuxing_str = _format_wuxing_fenbu(wuxing_fenbu)

    # 计算年龄和年龄阶段（先算 birth_year，供重点流年标注年龄使用）
    birth_year = int(birth_date.split('-')[0]) if birth_date and '-' in birth_date else 2000
    current_year = datetime.now().year
    age = current_year - birth_year

    # 重点流年格式化（传入 birth_year，在每个流年后标注对应年龄，防止LLM自己算错）
    key_liunian = analysis_data.get("重点流年", [])
    key_liunian_str = _format_key_liunian(key_liunian, birth_year=birth_year)

    # 用户问题涉及年份的流年+流月明细注入（重点流年只展示前5个，问题涉及的
    # 年份若不在其中会导致模型缺数据而编造——把该年完整数据直接注入消除编造动机）
    question_year_block = _format_question_year_block(
        key_liunian, user_question, birth_year,
        yongshen=analysis_data.get("用神", ""),
        jishen=analysis_data.get("忌神", ""),
    )
    if question_year_block:
        key_liunian_str = f"{key_liunian_str}\n\n{question_year_block}"

    # ── 命盘权威基准：生成者与评测者共用同一份（含25年干支表+问题年份12流月+边界），
    #    防止编造检测因"基准里没写报告里用了的年份"而误报。
    authoritative_basis = build_authoritative_chart_basis(analysis_data, user_question, birth_year)
    if authoritative_basis:
        key_liunian_str = f"{authoritative_basis}\n\n【重点流年精选（吉凶最高的前5条）】\n{key_liunian_str}"
    
    # 确定年龄阶段
    if age <= 12:
        age_stage = "儿童期（0-12岁）"
    elif age <= 17:
        age_stage = "青春期（13-17岁）"
    elif age <= 30:
        age_stage = "青年期（18-30岁）"
    elif age <= 50:
        age_stage = "中年期（31-50岁）"
    else:
        age_stage = "中老年期（51岁+）"

    context = {
        "current_time": time_info["current_time"],
        "liunian_ganzhi": time_info["liunian_ganzhi"],
        "liunian_season": time_info["liunian_season"],
        "sizu": sizu or MISSING_MARKER,
        "rizhu": analysis_data.get("日主") or MISSING_MARKER,
        "gender": gender,
        "wangshuai": analysis_data.get("旺衰结论") or MISSING_MARKER,
        "geju_description": analysis_data.get("格局") or MISSING_MARKER,
        "yongshen": analysis_data.get("用神") or MISSING_MARKER,
        "xishen": analysis_data.get("喜神", ""),
        "jishen": analysis_data.get("忌神") or MISSING_MARKER,
        "shishen_fenbu": analysis_data.get("十神分布", ""),
        "wuxing_fenbu": wuxing_str,
        "dizhi_zuoyong": analysis_data.get("地支作用", ""),
        "tiaohou_desc": analysis_data.get("调候描述", ""),
        "current_dayun": current_dayun_ganzhi or MISSING_MARKER,
        "dayun_jiedu": analysis_data.get("大运解读", ""),
        "key_liunian": key_liunian_str or MISSING_MARKER,
        "user_question": user_question,
        "age": age,
        "age_stage": age_stage,
        "birth_year": birth_year,
    }

    return context


# ============================================================
# 核心函数：构建专项 Skill Prompt
# ============================================================

def build_skill_prompt(
    analysis_data: Dict,
    gender: str,
    birth_date: str,
    birth_time: str,
    location: str,
    user_question: str,
    history: list,
    format_skill=None,
) -> str:
    """
    根据用户追问的问题类型，匹配对应的专项 prompt 模板，
    注入命盘数据后返回完整的 system prompt 字符串。

    参数:
        analysis_data: Orchestrator generate_full_analysis() 的完整输出
        gender: 性别
        birth_date: 出生日期
        birth_time: 出生时间
        location: 出生地
        user_question: 用户的具体追问问题
        history: 历史对话记录列表
        format_skill: FormatSkill实例，用于获取排版格式指令

    返回:
        完整的 system prompt 字符串
    """
    # 1. 从 analysis_data 提取所有需要的命盘字段
    context = _build_context_vars(analysis_data, gender, user_question, birth_date)

    # 2. 遍历 SKILL_PROMPTS，检查 user_question 是否包含任一关键词
    skill_type = _match_skill_type(user_question)

    # 3. 匹配到专项类型 -> 使用对应模板，注入命盘数据
    if skill_type:
        template = SKILL_PROMPTS[skill_type]["prompt"]
        prompt_body = template.format(**context)
    else:
        # 4. 未匹配 -> 使用通用追问 prompt，注入命盘数据
        prompt_body = GENERAL_FOLLOWUP_PROMPT.format(**context)

    # 5. 获取排版格式指令
    # 优先使用 FormatSkill 获取，降级使用本地 FORMAT_DIRECTIVE
    if format_skill and hasattr(format_skill, 'get_format_directive_sync'):
        format_directive = format_skill.get_format_directive_sync()
    else:
        format_directive = FORMAT_DIRECTIVE

    # 6. 追加排版指令（不注入历史对话，追问按独立专项报告生成，命盘数据已在上方注入）
    prompt_body += format_directive

    return prompt_body
