def _get_current_time_info() -> Dict[str, str]:
    """获取当前时间相关信息"""
    now = datetime.now()

    # 流年干支计算
    tiangan = ["甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸"]
    dizhi = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"]
    ganzhi_index = (now.year - 4) % 60
    liunian_ganzhi = tiangan[ganzhi_index % 10] + dizhi[ganzhi_index % 12]

    # 季节描述
    month = now.month
    if month in (3, 4, 5):
        liunian_season = "春季"
    elif month in (6, 7, 8):
        liunian_season = "夏季"
    elif month in (9, 10, 11):
        liunian_season = "秋季"
    else:
        liunian_season = "冬季"

    current_time = f"{now.year}年{now.month}月"

    return {
        "current_time": current_time,
        "liunian_ganzhi": liunian_ganzhi,
        "liunian_season": liunian_season,
    }


