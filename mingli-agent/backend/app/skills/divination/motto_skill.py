def _extract_climate_tag(
    month_di: str,
    tiaohou_yongshen: str,
    tiaohou_description: str,
) -> str:
    """
    提取调候标签。

    标签格式: "{气候特征}{调候用神五行}"
    例如: "寒火", "热水", "暖水", "凉火", "燥水"
    """
    season = YUE_LING_SEASON.get(month_di, "")

    # 从调候描述提取气候特征
    climate = ""
    desc = tiaohou_description or ""
    if any(kw in desc for kw in ("寒", "冻", "冷", "冰", "雪")):
        climate = "寒"
    elif any(kw in desc for kw in ("热", "炎", "酷", "暑")):
        climate = "热"
    elif any(kw in desc for kw in ("燥", "焦", "干")):
        climate = "燥"
    elif any(kw in desc for kw in ("暖", "温")):
        climate = "暖"
    else:
        climate = SEASON_CLIMATE.get(season, "")

    return f"{climate}{tiaohou_yongshen}"


def _get_wangshuai_suffix(wangshuai_conclusion: str) -> str:
    """
    根据旺衰结论返回后缀。

    返回:
        "身旺" / "身弱" / ""（平衡时返回空串）
    """
    ws = wangshuai_conclusion or ""
    if any(kw in ws for kw in ("身旺", "偏旺")):
        return "身旺"
    if any(kw in ws for kw in ("身弱", "偏弱", "太弱")):
        return "身弱"
    return ""


