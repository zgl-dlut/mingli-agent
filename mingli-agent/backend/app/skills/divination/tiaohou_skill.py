def calculate_tiaohou(day_tian: str, month_di: str) -> Dict:
    """
    计算调候用神

    参数:
        day_tian: 日主天干（如 "己"）
        month_di: 月令地支（如 "子"）

    返回:
    {
        "month_climate": {"name": "仲冬", "climate": "隆冬水旺，天寒地冻", "season": "冬"},
        "yongshen": "火",
        "xishen": "土",
        "jishen": "水",
        "tiaohou_description": "腊月寒土冰冻，火暖方能生木",
        "full_description": "己土生于子月（仲冬），隆冬水旺，天寒地冻。寒土需火暖方能化育，火为调候第一用神。喜燥土戊戌帮扶，忌水木克耗。"
    }
    """
    # 获取日主五行
    wuxing = TIANGAN_WUXING.get(day_tian)
    if wuxing is None:
        raise ValueError(f"无效的日主天干: {day_tian}，应为十天干之一（甲乙丙丁戊己庚辛壬癸）")

    # 获取月令气候
    month_climate = YUE_LING_CLIMATE.get(month_di)
    if month_climate is None:
        raise ValueError(f"无效的月令地支: {month_di}，应为十二地支之一（子丑寅卯辰巳午未申酉戌亥）")

    # 获取调候用神
    yongshen_info = TIAOHOU_YONGSHEN[wuxing][month_di]

    # 生成完整描述
    full_description = (
        f"{day_tian}{wuxing}生于{month_di}月（{month_climate['name']}），"
        f"{month_climate['climate']}。"
        f"{yongshen_info['调候描述']}，"
        f"{yongshen_info['用神']}为调候第一用神。"
        f"喜{yongshen_info['喜神']}帮扶，忌{yongshen_info['忌神']}克耗。"
    )

    return {
        "month_climate": month_climate,
        "yongshen": yongshen_info["用神"],
        "xishen": yongshen_info["喜神"],
        "jishen": yongshen_info["忌神"],
        "tiaohou_description": yongshen_info["调候描述"],
        "full_description": full_description,
    }